import Darwin
import Testing

@testable import UndoTurnCore

@Suite struct AgentHooksTests {
  @Test func settingsHookDispatcherRoundTripsDroidAndDevin() throws {
    let temporary = try TemporaryDirectory()
    let userHome = temporary.path + "/user"
    let cases: [(Agent, String)] = [
      (.droid, "Execute|Create|Edit|ApplyPatch"),
      (.devin, "exec|write|edit|apply_patch"),
    ]

    for (agent, matcher) in cases {
      #expect(AgentHooks.integration(for: agent) == .settingsHooks)
      let installed = try AgentHooks.install(
        agent: agent, executable: "/bin/undoturn", userHome: userHome, time: 10)
      #expect(installed.result == .installed)
      let path = AgentSettings.path(for: agent, userHome: userHome)
      let value = try JSONValue.parse(FileSystem.readFile(path))
      #expect(
        value["hooks"]?["PreToolUse"]?.arrayValue?.first?["matcher"] == .string(matcher))
      #expect(try AgentHooks.installedCommands(agent: agent, userHome: userHome).count == 3)
      #expect(try AgentHooks.missingHookEvents(agent: agent, userHome: userHome).isEmpty)
      #expect(
        try AgentHooks.install(
          agent: agent, executable: "/bin/undoturn", userHome: userHome, time: 20
        ).result == .unchanged)
      #expect(
        try AgentHooks.uninstall(agent: agent, userHome: userHome, time: 30).result == .removed)
    }
  }

  @Test func copilotHookFileInstallsIdempotentlyAndUninstalls() throws {
    let temporary = try TemporaryDirectory()
    let userHome = temporary.path + "/user"
    #expect(AgentHooks.integration(for: .copilot) == .undoTurnOwnedCopilotFile)

    let installed = try AgentHooks.install(
      agent: .copilot, executable: "/bin/undoturn", userHome: userHome, time: 10)
    let path = AgentSettings.path(for: .copilot, userHome: userHome)
    let value = try JSONValue.parse(FileSystem.readFile(path))
    #expect(installed.result == .installed)
    #expect(value["version"] == .integer(1))
    #expect(
      value["hooks"]?["userPromptSubmitted"]?.arrayValue?[0]["bash"]
        == .string("/bin/undoturn hook copilot start"))
    #expect(
      value["hooks"]?["preToolUse"]?.arrayValue?[0]["bash"]
        == .string("/bin/undoturn hook copilot tool"))
    #expect(
      value["hooks"]?["agentStop"]?.arrayValue?[0]["bash"]
        == .string("/bin/undoturn hook copilot stop"))
    #expect(try AgentHooks.installedCommands(agent: .copilot, userHome: userHome).count == 3)
    #expect(try AgentHooks.missingHookEvents(agent: .copilot, userHome: userHome).isEmpty)
    #expect(
      try AgentHooks.install(
        agent: .copilot, executable: "/bin/undoturn", userHome: userHome, time: 20
      ).result == .unchanged)
    #expect(
      try AgentHooks.uninstall(agent: .copilot, userHome: userHome, time: 30).result == .removed)
    #expect(try FileSystem.lstatIfPresent(path) == nil)
  }

  @Test func generatedExtensionsInstallIdempotentlyAndUninstall() throws {
    let temporary = try TemporaryDirectory()
    let userHome = temporary.path + "/user"
    let marker = "// Generated by undoturn init. undoturn uninstall removes this file.\n"

    for agent in [Agent.pi, .omp, .opencode] {
      #expect(AgentHooks.integration(for: agent) == .generatedExtensionFile)
      let installed = try AgentHooks.install(
        agent: agent, executable: "/bin/undoturn", userHome: userHome, time: 10)
      let path = AgentSettings.path(for: agent, userHome: userHome)
      let bytes = try FileSystem.readFile(path)
      let source = String(decoding: bytes, as: UTF8.self)
      let info = try #require(try FileSystem.lstatIfPresent(path))
      #expect(installed.result == .installed)
      #expect(source.hasPrefix(marker))
      #expect(!source.contains("__UNDOTURN__"))
      #expect(!source.contains("__AGENT__"))
      #expect(!source.contains("__TOOLS__"))
      #expect(info.st_mode & 0o777 == 0o644)
      #expect(
        try AgentHooks.installedCommands(agent: agent, userHome: userHome) == [
          "/bin/undoturn hook \(agent.rawValue)"
        ])
      #expect(try AgentHooks.missingHookEvents(agent: agent, userHome: userHome).isEmpty)
      #expect(
        try AgentHooks.install(
          agent: agent, executable: "/bin/undoturn", userHome: userHome, time: 20
        ).result == .unchanged)
      #expect(
        try AgentHooks.uninstall(agent: agent, userHome: userHome, time: 30).result == .removed)
      #expect(try FileSystem.lstatIfPresent(path) == nil)
    }
  }

  @Test func generatedExtensionRefusesForeignFileWithoutChangingIt() throws {
    let temporary = try TemporaryDirectory()
    let userHome = temporary.path + "/user"
    let path = AgentSettings.path(for: .pi, userHome: userHome)
    try FileSystem.makeDirectories(FileSystem.parent(of: path), mode: 0o755)
    let foreign = Array("export default function () {}\n".utf8)
    try FileSystem.writeAtomically(foreign, to: path, mode: 0o600, durable: false)

    #expect(throws: AgentHooksError.foreignFile(path: path)) {
      try AgentHooks.install(
        agent: .pi, executable: "/bin/undoturn", userHome: userHome, time: 10)
    }
    #expect(throws: AgentHooksError.foreignFile(path: path)) {
      try AgentHooks.uninstall(agent: .pi, userHome: userHome, time: 20)
    }
    #expect(try FileSystem.readFile(path) == foreign)
  }
}
