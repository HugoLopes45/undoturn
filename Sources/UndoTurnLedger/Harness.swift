/// A coding-agent harness that UndoTurn records, recognised from the agent name of a hook turn
/// or from the executable that an `undoturn run` turn started.
public enum Harness: String, CaseIterable, Sendable {
  case claude
  case codex
  case gemini
  case cursor
  case copilot
  case droid
  case devin
  case opencode
  case pi
  case omp

  /// `agent` is the name recorded with the turn; `command` is the prompt, which for a
  /// `undoturn run` turn is the command line it ran.
  public init?(agent: String, command: String?) {
    guard agent == "run" else {
      self.init(rawValue: agent)
      return
    }
    guard let word = command?.split(separator: " ").first,
      let executable = word.split(separator: "/").last
    else { return nil }
    self.init(rawValue: executable == "cursor-agent" ? "cursor" : String(executable))
  }

  public var name: String {
    switch self {
    case .claude: "Claude Code"
    case .codex: "Codex CLI"
    case .gemini: "Gemini CLI"
    case .cursor: "Cursor CLI"
    case .copilot: "Copilot CLI"
    case .droid: "Droid"
    case .devin: "Devin CLI"
    case .opencode: "OpenCode"
    case .pi: "Pi"
    case .omp: "Oh My Pi"
    }
  }

  /// Nil for Droid: no license covers the Factory logo.
  public var mark: HarnessMark? {
    switch self {
    case .claude: HarnessMarks.claude
    case .codex: HarnessMarks.codex
    case .gemini: HarnessMarks.gemini
    case .cursor: HarnessMarks.cursor
    case .copilot: HarnessMarks.copilot
    case .droid: nil
    case .devin: HarnessMarks.devin
    case .opencode: HarnessMarks.opencode
    case .pi: HarnessMarks.pi
    case .omp: HarnessMarks.omp
    }
  }
}

